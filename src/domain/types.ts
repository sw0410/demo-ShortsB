export type Mood = "any" | "calm" | "light" | "deep";
export type Goal = { unit: "pages"; value: number };
export type Profile = {
  life: string;
  mood: Mood;
  thought: string;
  topics?: string[];
};
export type Guide = {
  hook: string;
  reason: string;
  scene: string;
  context: string;
  start: number;
  anchor: string;
  keywords: string[];
  intent: string;
  note: string;
};
export type Chapter = {
  id: string;
  title: string;
  start: number;
  end: number;
  available: boolean;
};
export type Book = {
  id: string;
  book: string;
  author: string;
  originalTitle: string;
  aliases: string[];
  topics: string[];
  moods: string[];
  keywords: string[];
  description: string;
  theme: string;
  tone: string;
  workType: "short" | "novella" | "novel";
  parts: string[];
  edition: string;
  editionLabel: string;
  translationNote: string;
  available: boolean;
  textLanguage: string;
  pageJoiner: string;
  totalPages: number;
  chapters: Chapter[];
  guide: Guide;
  source: string;
  sourceName: string;
  licenseURL?: string;
  licenseLabel?: string;
  credits?: string;
  legacyEditions: Record<string, number>;
  defaultLegacyEdition: string;
};
export type Relation = {
  target: string;
  title: string;
  reason: string;
  kind: string;
  fromLabel: string;
  toLabel: string;
};
export type Session = {
  id: string;
  edition: string;
  start: number;
  cursor: number;
  end: number;
  mode: "trial" | "book" | "excerpt";
  token: string;
  completed: boolean;
  recommendationTrail: string[];
  scrollY: number;
  updatedAt: number;
};
export type ReadRecord = {
  id: string;
  edition: string;
  index: number;
  day: string;
};
export type History = Session & { day: string };
export type Highlight = {
  id: string;
  bookId: string;
  edition: string;
  index: number;
  start: number;
  end: number;
  text: string;
};
export type State = {
  version: 4;
  profile: Profile | null;
  goal: Goal;
  goalDays: Record<string, Goal>;
  readingSeconds: Record<string, number>;
  pageCount: number;
  manualDose: boolean;
  saved: string[];
  completedDays: string[];
  readLog: ReadRecord[];
  history: History[];
  progress: Record<string, Session>;
  active: Session | null;
  finished: Session | null;
  highlights: Highlight[];
  feedback: Record<string, string>;
  intro: { bookId: string; status: "reading" | "done" } | null;
  setupCompleted: boolean;
  /** Browser-persisted demo login status; independent of preferences and reading history. */
  demoAccountComplete: boolean;
  demoUserId: string | null;
  guestContinue: boolean;
  fontLarge: boolean;
  calendarDemo: boolean;
  editionArchive: Record<string, unknown>;
  catalogEditions: Record<string, string>;
};
